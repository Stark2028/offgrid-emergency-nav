import { expect, test } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
import { readFileSync } from 'node:fs';
import { Tile, TileSet } from '@offgrid/core';
import { WalkingNetwork } from '@offgrid/maps';
import { pickMapPoints } from '../tools/map-test-points.mjs';
import catalogue from '../src/generated/catalog.json' with { type: 'json' };

test('saved walking routes work entirely offline and reject unusable locations', async ({ page, context }, testInfo) => {
  const errors: string[]=[]; page.on('pageerror', e=>errors.push(e.message));
  await page.goto('/');
  // This region has a richer OSM place list than the Central Delhi snapshot.
  await page.getByRole('button', {name:/South Delhi Hauz Khas/}).click();
  await page.getByRole('button', {name:/Download this area/}).click();
  await expect(page.getByText('Saved on this device', {exact:true})).toBeVisible();
  await page.evaluate(async()=>{await navigator.serviceWorker.ready;});
  await expect.poll(()=>page.evaluate(()=>!!navigator.serviceWorker.controller)).toBe(true);
  await context.setOffline(true); await page.reload();
  await page.getByRole('button', {name:'Open walking navigation'}).click();
  await expect(page.getByRole('heading', {name:'Where are you heading?'})).toBeVisible();
  await page.getByLabel('Find a place within this saved area').fill('Hauz');
  const places=page.locator('.place-results button');
  await expect(places.first()).toBeVisible();
  await places.first().click();
  // Deterministic points on the actual saved walking graph, selected through
  // map interactions so the worker, UI, and coordinate transform are exercised.
  await page.locator('.point-field').first().click();
  await page.getByLabel('Find a place within this saved area').fill('');
  const map=page.locator('.navigation-map:not(.coverage-map)');
  await expect(map).toHaveAttribute('data-ready','true');
  const selectedStart=(await page.locator('.point-field').first().locator('strong').textContent())!;
  const marker=page.locator('.map-point-start'),before=(await marker.boundingBox())!;
  const canvas=map.locator('canvas.maplibregl-canvas');
  await canvas.scrollIntoViewIfNeeded();
  const area=(await canvas.boundingBox())!;
  await page.mouse.move(area.x+area.width*.45,area.y+area.height*.5);
  await page.mouse.down();
  await page.mouse.move(area.x+area.width*.65,area.y+area.height*.5,{steps:12});
  await page.mouse.up();
  await expect.poll(async()=>Math.abs((await marker.boundingBox())!.x-before.x)).toBeGreaterThan(25);
  await expect(page.locator('.point-field').first().locator('strong')).toHaveText(selectedStart);
  await page.getByRole('button',{name:'Show whole area',exact:true}).click();
  const region=catalogue.regions.find(r=>r.id==='south-delhi-starter') ?? catalogue.regions.find(r=>r.name==='South Delhi')!;
  const folder=resolve(import.meta.dirname,'../public',region.manifestUrl.slice(1),'..');
  const manifest=JSON.parse(readFileSync(resolve(folder,'manifest.json'),'utf8'));
  const tiles=new TileSet();
  for (const asset of manifest.assets.filter((a:{kind:string})=>a.kind==='routing-tile')) {
    const bytes=Uint8Array.from(readFileSync(resolve(folder,asset.path)));tiles.add(new Tile(bytes.buffer));
  }
  const network=new WalkingNetwork(tiles),[w,s,e,n]=region.bounds;
  const edge=network.edges.find(edge=>edge.metres>100 && edge.points.every(([lon,lat])=>lon>w! && lon<e! && lat>s! && lat<n!))!;
  await pickMapPoints(page, region.bounds, [edge.points[0]!,edge.points[edge.points.length-1]!]);
  await page.getByRole('button', {name:'Find walking route',exact:true}).click();
  await expect(page.locator('.route-summary')).toBeVisible({timeout:20000});
  await expect(page.locator('.navigation-map')).toHaveAttribute('data-route-ready','true');
  await expect(page.getByRole('heading',{name:'Your walking route.'})).toBeFocused();
  await page.getByText(/Route directions/).click();
  await expect(page.getByText('Follow the highlighted walking path')).toBeVisible();
  const dir=resolve(import.meta.dirname,'../../../.impeccable/review'); await mkdir(dir,{recursive:true});
  await page.screenshot({path:resolve(dir,`${testInfo.project.name}-navigation.png`),fullPage:true});
  await context.grantPermissions(['geolocation']);
  await context.setGeolocation({latitude:edge.points[0]![1],longitude:edge.points[0]![0],accuracy:10});
  await page.getByRole('button',{name:'Start location guidance'}).click();
  await expect(page.getByRole('region',{name:'Current walking guidance'})).toBeVisible();
  await expect(page.locator('.point-field')).toHaveCount(0);
  const pause=page.getByRole('button',{name:'Pause guidance'}),pauseBox=(await pause.boundingBox())!;
  expect(pauseBox.y+pauseBox.height).toBeLessThan(page.viewportSize()!.height);
  await page.screenshot({path:resolve(dir,`${testInfo.project.name}-guidance.png`),fullPage:true});
  await pause.click();
  await page.locator('.point-field').last().click();
  await expect(page.getByLabel('Find a place within this saved area')).toBeFocused();
  await context.setGeolocation({latitude:19.076,longitude:72.8777,accuracy:10});
  await page.getByRole('button',{name:'Use my location as start'}).click();
  await expect(page.getByRole('alert')).toContainText('outside this saved area');
  await context.setGeolocation({latitude:28.557,longitude:77.205,accuracy:200});
  await page.getByRole('button',{name:'Use my location as start'}).click();
  await expect(page.getByRole('alert')).toContainText('too approximate');
  const locationButton=(await page.getByRole('button',{name:'Use my location as start'}).boundingBox())!;
  const feedback=(await page.getByRole('alert').boundingBox())!;
  expect(feedback.y-locationButton.y-locationButton.height).toBeLessThan(45);
  await page.getByRole('button',{name:'Back to map library'}).click();
  await expect(page.getByRole('heading',{name:'Hauz Khas & Green Park'})).toBeVisible();
  expect(errors).toEqual([]);
});

test('Prayagraj city pack installs, survives offline reopening, and plans a covered walking route', async ({page,context},testInfo) => {
  test.setTimeout(180000);
  const errors: string[]=[];page.on('pageerror',e=>errors.push(e.message));
  const region=catalogue.regions.find(r=>r.id==='prayagraj-city')!;
  const folder=resolve(import.meta.dirname,'../public',region.manifestUrl.slice(1),'..');
  const manifest=JSON.parse(readFileSync(resolve(folder,'manifest.json'),'utf8')),tiles=new TileSet();
  for(const asset of manifest.assets.filter((a:{kind:string})=>a.kind==='routing-tile')) tiles.add(new Tile(Uint8Array.from(readFileSync(resolve(folder,asset.path))).buffer));
  const network=new WalkingNetwork(tiles,region.bounds as [number,number,number,number]);
  const edge=network.edges.find(e=>e.metres>200 && tiles.component(e.source)===0)!;
  await page.goto('/');
  await expect(page.getByRole('heading',{name:'City & river crossings'})).toBeVisible();
  await page.getByRole('button',{name:/Download this area/}).click();
  await expect(page.getByText('Saved on this device',{exact:true})).toBeVisible({timeout:120000});
  await expect(page.locator('.coverage-map')).toHaveAttribute('data-ready','true',{timeout:30000});
  await page.evaluate(async()=>{await navigator.serviceWorker.ready;});
  await expect.poll(()=>page.evaluate(()=>!!navigator.serviceWorker.controller)).toBe(true);
  await context.setOffline(true); await page.reload();
  await page.getByRole('button',{name:'Open walking navigation'}).click();
  await page.getByLabel('Find a place within this saved area').fill('Civil Lines');
  await expect(page.locator('.place-results button').first()).toBeVisible();
  await page.getByLabel('Find a place within this saved area').fill('');
  await pickMapPoints(page,region.bounds,[edge.points[0]!,edge.points[edge.points.length-1]!]);
  await page.getByRole('button',{name:'Find walking route',exact:true}).click();
  await expect(page.locator('.route-summary')).toBeVisible({timeout:30000});
  await expect(page.getByText(`${region.areaKm2} km² saved area`,{exact:true})).toBeVisible();
  await expect(page.locator('.navigation-map')).toHaveAttribute('data-route-ready','true');
  const dir=resolve(import.meta.dirname,'../../../.impeccable/review');await mkdir(dir,{recursive:true});
  await page.screenshot({path:resolve(dir,`${testInfo.project.name}-prayagraj.png`),fullPage:true});
  expect(errors).toEqual([]);
});
